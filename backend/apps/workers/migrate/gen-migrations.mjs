// Inlines backend/migrations/*.sql (sorted by filename) into
// src/migrations.generated.ts so esbuild bundles the DDL — the Lambda zip ships
// no .sql files, so there's no runtime fs read. Re-run after adding a migration:
//   node apps/workers/migrate/gen-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, '../../../migrations');
const outFile = join(here, 'src/migrations.generated.ts');

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const entries = files
  .map((file) => {
    const sql = readFileSync(join(migrationsDir, file), 'utf8');
    return `  { file: ${JSON.stringify(file)}, sql: ${JSON.stringify(sql)} },`;
  })
  .join('\n');

const body = `// GENERATED by gen-migrations.mjs — do not edit. Raw SQL inlined from
// backend/migrations/*.sql so esbuild bundles it (no runtime fs).
export const MIGRATIONS: { file: string; sql: string }[] = [
${entries}
];
`;

writeFileSync(outFile, body);
console.log(`wrote ${files.length} migration(s) to ${outFile}`);
